#include<iostream>
using namespace std;
int main(){
    // This Are the Primitive Datatypes in C++.
    int age=19; //Size of int is 4 bytes.
    char Grade='A'; //Size of char is 1 byte.
    float Weight=60.5f; //Size of float is 4 bytes.
    bool isstudent= true; //Size of bool is 1 byte.
    double Score=99.99; //Size of double is 8 bytes.
    cout<<age<<endl;
    cout<<Grade<<endl;
    cout<<Weight<<endl;
    cout<<isstudent<<endl;
    cout<<Score;
    return 0;
}